import { expect,test } from '@playwright/test';
test('manual views keep tiles and mobile scroll stable during speaker updates',async({page,isMobile})=>{
  if(isMobile)await page.setViewportSize({width:390,height:440});
  await page.goto('/layout-test/conference');
  const tiles=page.locator('[data-track-key]');await expect(tiles).toHaveCount(8);
  await expect(page.getByLabel('View',{exact:true})).toHaveValue('grid');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const boxes=await tiles.evaluateAll(nodes=>nodes.map(node=>{const r=node.getBoundingClientRect();return {left:r.left,top:r.top,bottom:r.bottom};}));
  const column=boxes.filter(box=>Math.abs(box.left-boxes[0].left)<1).sort((a,b)=>a.top-b.top);
  for(let n=1;n<column.length;n++)expect(column[n].top).toBeGreaterThanOrEqual(column[n-1].bottom-1);
  await page.evaluate(()=>{
    const root=document.querySelector('.wbify-tiles')!;
    (window as unknown as {tileRemovals:number}).tileRemovals=0;
    new MutationObserver(records=>{for(const record of records)for(const node of record.removedNodes){if(node instanceof HTMLElement && node.matches('[data-track-key]'))(window as unknown as {tileRemovals:number}).tileRemovals++;}}).observe(root,{childList:true});
  });
  const before=await tiles.evaluateAll(nodes=>nodes.map(n=>n.getAttribute('data-track-key')));
  const localVideo=page.locator('[data-track-key] video').first();
  await expect(localVideo).toBeAttached();
  await localVideo.evaluate(node=>node.setAttribute('data-video-instance','stable'));
  await page.locator('.wbify-tiles').evaluate(n=>{n.scrollTop=100;});
  const scroll=await page.locator('.wbify-tiles').evaluate(n=>n.scrollTop);
  if(isMobile)expect(scroll).toBeGreaterThan(0);
  for(let n=0;n<6;n++)await page.getByRole('button',{name:'Change active speaker'}).click();
  expect(await tiles.evaluateAll(nodes=>nodes.map(n=>n.getAttribute('data-track-key')))).toEqual(before);
  expect(await page.locator('.wbify-tiles').evaluate(n=>n.scrollTop)).toBe(scroll);
  expect(await page.evaluate(()=>(window as unknown as {tileRemovals:number}).tileRemovals)).toBe(0);
  await expect(page.locator('video[data-video-instance="stable"]')).toHaveCount(1);
  await page.screenshot({path:`test-results/meeting-grid-${isMobile?'mobile':'desktop'}.png`,fullPage:true});
  await page.getByLabel('View',{exact:true}).selectOption('spotlight');
  const focus=page.getByLabel('Focus',{exact:true});
  await focus.selectOption(before[3]!);
  const selected=await focus.inputValue();
  await page.getByRole('button',{name:'Change active speaker'}).click();
  await expect(focus).toHaveValue(selected);
  await expect(page.locator('.wbify-focused')).toHaveAttribute('data-track-key',selected);
  await page.getByLabel('View',{exact:true}).selectOption('sidebar');
  await expect(focus).toHaveValue(selected);
  await page.screenshot({path:`test-results/meeting-sidebar-${isMobile?'mobile':'desktop'}.png`,fullPage:true});
  await page.getByLabel('View',{exact:true}).selectOption('grid');
  expect(await tiles.evaluateAll(nodes=>nodes.map(n=>n.getAttribute('data-track-key')))).toEqual(before);
  expect(await page.evaluate(()=>(window as unknown as {tileRemovals:number}).tileRemovals)).toBe(0);
  await expect(page.locator('video[data-video-instance="stable"]')).toHaveCount(1);
});
